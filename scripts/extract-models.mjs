#!/usr/bin/env node
// Extract the OpenCode Zen model catalogs that are embedded in the opencode CLI binary
// and emit them as a Go source file (models_gen.go).
//
// Usage:
//   node scripts/extract-models.mjs [path/to/opencode] [out/models_gen.go]
//
// The catalog lives in the minified bundle inside the binary as
//   ...opencode:{id:"opencode",env:["OPENCODE_API_KEY"],npm:"@ai-sdk/openai-compatible",
//      api:"https://opencode.ai/zen/v1",name:"OpenCode Zen",...,models:{"<id>":{...}}}
//   ..."opencode-go":{id:"opencode-go",...,api:"https://opencode.ai/zen/go/v1",...,models:{...}}
//
// A model is free when cost.input === 0 (this is exactly the rule the CLI itself uses
// to hide paid models from anonymous users).

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { execFileSync } from "node:child_process";

const OPENCODE_BIN =
  process.argv[2] ??
  process.env.OPENCODE_BIN ??
  (() => {
    try {
      return execFileSync("bash", ["-lc", "readlink -f $(command -v opencode)"], { encoding: "utf8" }).trim();
    } catch {
      return null;
    }
  })();

if (!OPENCODE_BIN) {
  console.error("cannot locate the opencode binary; pass it as argv[2] or set OPENCODE_BIN");
  process.exit(1);
}

const OUT = resolve(process.argv[3] ?? "models_gen.go");
const text = readFileSync(OPENCODE_BIN, "latin1");

/** Find `needle`, then return the balanced-brace object that starts right after it. */
function balancedObject(source, needle, from = 0) {
  const at = source.indexOf(needle, from);
  if (at < 0) return null;
  let i = source.indexOf("{", at);
  if (i < 0) return null;
  let depth = 0;
  let quote = null;
  for (let k = i; k < source.length; k++) {
    const c = source[k];
    if (quote) {
      if (c === "\\") k++;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") quote = c;
    else if (c === "{") depth++;
    else if (c === "}" && --depth === 0) return source.slice(i, k + 1);
  }
  return null;
}

function parseModels(block) {
  if (!block) return [];
  const models = {};
  const re = /\{id:"([A-Za-z0-9._-]+)",name:"((?:[^"\\]|\\.)*)"/g;
  const hits = [];
  let m;
  while ((m = re.exec(block))) hits.push({ id: m[1], name: m[2], start: m.index });
  hits.forEach((hit, idx) => {
    const body = block.slice(hit.start, idx + 1 < hits.length ? hits[idx + 1].start : block.length);
    const cost = /cost:\{input:([0-9.eE+-]+),output:([0-9.eE+-]+)/.exec(body);
    const limit = /limit:\{context:([0-9.eE+-]+)/.exec(body);
    models[hit.id] = {
      id: hit.id,
      name: hit.name.replace(/\\"/g, '"').replace(/\\'/g, "'"),
      costInput: cost ? Number(cost[1]) : null,
      costOutput: cost ? Number(cost[2]) : null,
      context: limit ? Number(limit[1]) : 0,
    };
  });
  return Object.values(models);
}

const zen = parseModels(balancedObject(text, 'opencode:{id:"opencode"'));
const go = parseModels(balancedObject(text, '"opencode-go":{id:"opencode-go"'));

if (!zen.length || !go.length) {
  console.error(`extraction failed (zen=${zen.length}, go=${go.length}); opencode layout may have changed`);
  process.exit(1);
}

const version = (() => {
  if (process.env.OPENCODE_VERSION) return process.env.OPENCODE_VERSION;
  for (const cmd of [[OPENCODE_BIN, ["--version"]], ["bash", ["-lc", "opencode --version"]]]) {
    try {
      const v = execFileSync(cmd[0], cmd[1], { encoding: "utf8" }).trim();
      if (v) return v;
    } catch {}
  }
  return "unknown";
})();

const goLiteral = (models) =>
  models
    .map(
      (m) =>
        `\t{ID: ${JSON.stringify(m.id)}, Name: ${JSON.stringify(m.name)}, ` +
        `CostInput: ${m.costInput ?? 0}, CostOutput: ${m.costOutput ?? 0}, Context: ${m.context}}`,
    )
    .join(",\n");

const out = `// Code generated by scripts/extract-models.mjs from opencode-ai ${version}; DO NOT EDIT.
//
// Source: the model catalog embedded in the opencode CLI binary.
// Free models are the entries with CostInput == 0 — the same rule the CLI uses to
// hide paid models from anonymous (apiKey "public") users.

package main

// ZenModels is the full catalog served by https://opencode.ai/zen/v1.
var ZenModels = []Model{
${goLiteral(zen)},
}

// GoModels is the catalog served by https://opencode.ai/zen/go/v1 (OpenCode Go subscription).
var GoModels = []Model{
${goLiteral(go)},
}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out);
const free = zen.filter((m) => m.costInput === 0);
console.log(
  `wrote ${OUT}: zen=${zen.length} (free=${free.length}), go=${go.length}, opencode ${version}`,
);
